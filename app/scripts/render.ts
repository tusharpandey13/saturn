// Render deploy templates from an env file (the env repo's env.yaml) and check an env file against env.manifest.yaml.
//   render.ts [wrangler] [--env FILE]   -> app/wrangler.toml (used by wrangler dev/deploy, e2e:local, db:migrate:local)
//   render.ts check [--env FILE]        -> exit 1 if a manifest var is missing or mistyped
// FILE defaults to $ENV_FILE, then deploy/env.example.yaml. ${a.b} = a value; a line with ${?a.b} is dropped when the
// value is empty or missing (optional values such as an unpinned D1 id).
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { parseArgs } from "node:util";
import { parse } from "yaml";

const ROOT = join(import.meta.dirname, "..", "..");
const { positionals, values } = parseArgs({ allowPositionals: true, options: { env: { type: "string" } } });
const envFile = resolve(values.env || process.env.ENV_FILE || join(ROOT, "deploy", "env.example.yaml"));
const die = (m: string): never => {
  console.error(`render: ${m}`);
  process.exit(1);
  throw new Error(m);
};
const get = (o: unknown, path: string): unknown => path.split(".").reduce<any>((a, k) => (a == null ? undefined : a[k]), o);
const empty = (v: unknown) => v === undefined || v === null || v === "";

export function render(tpl: string, env: unknown, what = "template"): string {
  return tpl
    .split("\n")
    .filter((line) => ![...line.matchAll(/\$\{\?([\w.]+)\}/g)].some((m) => empty(get(env, m[1]))))
    .join("\n")
    .replace(/\$\{\??([\w.]+)\}/g, (_, p: string) => {
      const v = get(env, p);
      if (empty(v)) die(`${what}: ${p} is not set in ${envFile}`);
      const s = String(v);
      if (/["'\n\\]/.test(s)) die(`${what}: ${p} may not contain a quote, backslash or newline`);
      return s;
    });
}

export function check(env: any, manifest: any): string[] {
  const errs: string[] = [];
  if (env?.schema !== manifest.env_schema) errs.push(`schema: expected ${manifest.env_schema}, got ${env?.schema}`);
  for (const [p, t] of Object.entries<string>(manifest.vars)) {
    const optional = t.endsWith("?");
    const type = t.replace(/\?$/, "");
    const v = get(env, p);
    if (empty(v)) {
      if (!optional) errs.push(`${p}: required (${type})`);
      continue;
    }
    const ok = type === "map" ? typeof v === "object" && !Array.isArray(v) : type === "int" ? Number.isInteger(v) : type === "bool" ? typeof v === "boolean" : typeof v === "string";
    if (!ok) errs.push(`${p}: expected ${type}`);
  }
  for (const [k, list] of [["batch.llm_adapter", manifest.adapters.llm], ["batch.stt_adapter", manifest.adapters.stt], ["ack_mode", manifest.ack_modes ?? []], ["context_mode", manifest.context_modes ?? []]] as const) {
    const v = get(env, k);
    if (!empty(v) && !list.includes(v)) errs.push(`${k}: ${v} is not one of ${list.join(", ")}`);
  }
  return errs;
}

if (import.meta.main ?? process.argv[1]?.endsWith("render.ts")) {
  const env = parse(readFileSync(envFile, "utf8"));
  const cmd = positionals[0] ?? "wrangler";
  if (cmd === "check") {
    const errs = check(env, parse(readFileSync(join(ROOT, "env.manifest.yaml"), "utf8")));
    for (const e of errs) console.error(`env check: ${e}`);
    if (errs.length) process.exit(1);
    console.log(`env check: ok (${envFile})`);
  } else if (cmd === "wrangler") {
    const out = join(ROOT, "app", "wrangler.toml");
    const body = render(readFileSync(join(ROOT, "deploy", "wrangler.template.toml"), "utf8"), env, "wrangler");
    writeFileSync(out, `# GENERATED by app/scripts/render.ts from ${envFile.startsWith(ROOT) ? envFile.slice(ROOT.length + 1) : "an env file"}; do not edit.\n${body}`);
    console.log("render: app/wrangler.toml");
  } else die(`unknown command ${cmd} (wrangler | check)`);
}
